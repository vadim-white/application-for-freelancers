import os
import pathlib
import uuid
from types import SimpleNamespace

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect, text
from sqlalchemy.exc import IntegrityError

SERVICE_ROOT = pathlib.Path(__file__).resolve().parent.parent

TABLES = {"projects", "tasks"}
# типы enum, которые создаёт миграция в PostgreSQL (в SQLite их нет)
EXPECTED_ENUMS = {"taskstatus"}


@pytest.fixture(params=["sqlite", "postgres"])
def migrations_db(request, tmp_path):
    """Пустая база для миграций: DATABASE_URL из conftest занят базой остальных тестов.

    sqlite — отдельный файл. postgres — своя схема (search_path) в базе из TEST_POSTGRES_URL
    (postgresql+psycopg://…), она создаётся перед тестом и удаляется после; без переменной тест пропускается.
    Соединение передаётся в migrations/env.py через cfg.attributes["connection"].
    """
    schema = None
    if request.param == "sqlite":
        engine = create_engine(f"sqlite:///{tmp_path}/migrations.db")
    else:
        url = os.environ.get("TEST_POSTGRES_URL")
        if not url:
            pytest.skip("TEST_POSTGRES_URL не задана: тест миграций на PostgreSQL пропущен")
        schema = f"mig_{uuid.uuid4().hex[:12]}"
        admin = create_engine(url, isolation_level="AUTOCOMMIT")
        with admin.connect() as conn:
            conn.execute(text(f"CREATE SCHEMA {schema}"))
        # таблицы и типы enum создаются в этой схеме и не мешают остальным базам и тестам
        engine = create_engine(url, connect_args={"options": f"-csearch_path={schema}"})
    cfg = Config(str(SERVICE_ROOT / "alembic.ini"))

    def run(cmd, *args):
        with engine.begin() as connection:
            cfg.attributes["connection"] = connection
            cmd(cfg, *args)

    def tables():
        return set(inspect(engine).get_table_names())

    def enums():
        """Имена типов enum в схеме теста (в SQLite типов нет)."""
        if schema is None:
            return set()
        query = text(
            "SELECT t.typname FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace "
            "WHERE n.nspname = :schema AND t.typtype = 'e'"
        )
        with engine.connect() as conn:
            return set(conn.execute(query, {"schema": schema}).scalars())

    # база чистая до теста
    assert tables() == set()
    assert enums() == set()

    yield SimpleNamespace(backend=request.param, engine=engine, run=run, tables=tables, enums=enums)

    engine.dispose()
    if schema is not None:
        with admin.connect() as conn:
            conn.execute(text(f"DROP SCHEMA {schema} CASCADE"))
        admin.dispose()


def test_upgrade_head_matches_models(migrations_db):
    db = migrations_db
    db.run(command.upgrade, "head")
    assert db.tables() == {"alembic_version"} | TABLES
    # типы enum есть только в PostgreSQL
    assert db.enums() == (EXPECTED_ENUMS if db.backend == "postgres" else set())
    # Падает с AutogenerateDiffsDetected, если модели и миграции расходятся
    db.run(command.check)


def test_downgrade_base_then_upgrade_again(migrations_db):
    db = migrations_db
    db.run(command.upgrade, "head")
    db.run(command.downgrade, "base")
    # ни таблиц, ни типов enum: PostgreSQL не удаляет тип вместе с таблицей (см. downgrade)
    assert db.tables() == {"alembic_version"}
    assert db.enums() == set()
    db.run(command.upgrade, "head")
    assert db.tables() == {"alembic_version"} | TABLES
    db.run(command.check)


# SQLite не проверяет внешние ключи по умолчанию, поэтому FK проверяется только на PostgreSQL
@pytest.mark.parametrize("migrations_db", ["postgres"], indirect=True)
def test_task_project_foreign_key_enforced(migrations_db):
    db = migrations_db
    db.run(command.upgrade, "head")
    insert_task = text(
        "INSERT INTO tasks (title, status, owner_id, is_active, project_id) "
        "VALUES ('t', 'todo', 1, true, :project_id)"
    )
    with db.engine.begin() as conn:
        project_id = conn.execute(
            text("INSERT INTO projects (name, owner_id, is_active) VALUES ('p', 1, true) RETURNING id")
        ).scalar_one()
        # задача с существующим проектом вставляется (проверка, что ошибка ниже именно из-за FK)
        conn.execute(insert_task, {"project_id": project_id})
    with pytest.raises(IntegrityError, match="foreign key"):
        with db.engine.begin() as conn:
            conn.execute(insert_task, {"project_id": project_id + 1000})
