import pathlib

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import create_engine, inspect

SERVICE_ROOT = pathlib.Path(__file__).resolve().parent.parent


@pytest.fixture
def migrations_db(tmp_path):
    """Отдельная пустая SQLite: DATABASE_URL из conftest занят базой остальных тестов.

    Соединение передаётся в migrations/env.py через cfg.attributes["connection"].
    """
    engine = create_engine(f"sqlite:///{tmp_path}/migrations.db")
    cfg = Config(str(SERVICE_ROOT / "alembic.ini"))

    def run(cmd, *args):
        with engine.begin() as connection:
            cfg.attributes["connection"] = connection
            cmd(cfg, *args)

    def tables():
        return set(inspect(engine).get_table_names())

    yield run, tables
    engine.dispose()


def test_upgrade_head_matches_models(migrations_db):
    run, tables = migrations_db
    run(command.upgrade, "head")
    assert tables() == {"alembic_version", "users"}
    # Падает с AutogenerateDiffsDetected, если модели и миграции расходятся
    run(command.check)


def test_downgrade_base_then_upgrade_again(migrations_db):
    run, tables = migrations_db
    run(command.upgrade, "head")
    run(command.downgrade, "base")
    assert tables() == {"alembic_version"}
    run(command.upgrade, "head")
    assert tables() == {"alembic_version", "users"}
    run(command.check)
