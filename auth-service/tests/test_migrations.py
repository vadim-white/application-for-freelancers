import pytest
from alembic import command
from sqlalchemy import inspect, text

TABLES = {"users", "user_audit", "login_attempts"}
# типы enum, которые создаёт миграция в PostgreSQL (в SQLite их нет)
EXPECTED_ENUMS = {"userrole"}
CREATE_USERS = "d68b21b4476c"
EMAIL_LOWERCASE = "37998bcc3290"
USER_AUDIT = "6f0e3b36cb48"


def test_upgrade_head_matches_models(migrations_db):
    db = migrations_db
    db.run(command.upgrade, "head")
    assert db.tables() == {"alembic_version"} | TABLES
    # типы enum есть только в PostgreSQL
    assert db.enums() == (EXPECTED_ENUMS if db.backend == "postgres" else set())
    # Падает с AutogenerateDiffsDetected, если модели и миграции расходятся
    db.run(command.check)


def test_downgrade_base_then_upgrade_again(migrations_db):
    db = migrations_db
    db.run(command.upgrade, "head")
    db.run(command.downgrade, "base")
    # ни таблиц, ни типов enum: PostgreSQL не удаляет тип вместе с таблицей (см. downgrade)
    assert db.tables() == {"alembic_version"}
    assert db.enums() == set()
    db.run(command.upgrade, "head")
    assert db.tables() == {"alembic_version"} | TABLES
    db.run(command.check)


def insert_users(db, *emails):
    with db.engine.begin() as conn:
        for email in emails:
            conn.execute(
                text(
                    "INSERT INTO users (email, hashed_password, is_active, role) "
                    "VALUES (:email, 'x', true, 'user')"
                ),
                {"email": email},
            )


def emails(db):
    with db.engine.connect() as conn:
        return conn.execute(text("SELECT email FROM users ORDER BY id")).scalars().all()


def revision(db):
    with db.engine.connect() as conn:
        return conn.execute(text("SELECT version_num FROM alembic_version")).scalar_one()


def test_email_lowercase_migration(migrations_db):
    db = migrations_db
    db.run(command.upgrade, CREATE_USERS)
    insert_users(db, "User1@example.com", "user2@example.com", "ADMIN@EXAMPLE.COM")
    db.run(command.upgrade, "head")
    lowered = ["user1@example.com", "user2@example.com", "admin@example.com"]
    assert emails(db) == lowered

    # downgrade регистр не возвращает, повторный upgrade ничего не меняет
    db.run(command.downgrade, CREATE_USERS)
    assert emails(db) == lowered
    db.run(command.upgrade, "head")
    assert emails(db) == lowered
    db.run(command.check)


def test_email_lowercase_migration_stops_on_duplicates(migrations_db):
    db = migrations_db
    db.run(command.upgrade, CREATE_USERS)
    before = ["User1@example.com", "user1@example.com", "Solo@Example.com"]
    insert_users(db, *before)
    with pytest.raises(RuntimeError, match="user1@example.com") as exc:
        db.run(command.upgrade, "head")
    assert "solo@example.com" not in str(exc.value)
    assert emails(db) == before
    assert revision(db) == CREATE_USERS


def test_user_audit_migration_keeps_users(migrations_db):
    db = migrations_db
    db.run(command.upgrade, EMAIL_LOWERCASE)
    insert_users(db, "user1@example.com", "admin@example.com")
    db.run(command.upgrade, "head")
    assert "user_audit" in db.tables()
    with db.engine.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO user_audit (actor_id, target_id, field, old_value, new_value) "
                "VALUES (2, 1, 'role', 'user', 'admin')"
            )
        )
        created = conn.execute(text("SELECT created_at FROM user_audit")).scalar_one()
    assert created is not None

    # downgrade удаляет только журнал, пользователи остаются
    db.run(command.downgrade, EMAIL_LOWERCASE)
    assert db.tables() == {"alembic_version", "users"}
    assert emails(db) == ["user1@example.com", "admin@example.com"]
    db.run(command.upgrade, "head")
    db.run(command.check)


def test_login_attempts_migration_keeps_users(migrations_db):
    db = migrations_db
    db.run(command.upgrade, USER_AUDIT)
    insert_users(db, "user1@example.com")
    db.run(command.upgrade, "head")
    indexes = {i["name"] for i in inspect(db.engine).get_indexes("login_attempts")}
    assert indexes == {"ix_login_attempts_window_start"}
    with db.engine.begin() as conn:
        conn.execute(
            text(
                "INSERT INTO login_attempts (email, attempts, window_start) "
                "VALUES ('user1@example.com', 1, CURRENT_TIMESTAMP)"
            )
        )

    # downgrade удаляет только счётчик, пользователи и журнал остаются
    db.run(command.downgrade, USER_AUDIT)
    assert db.tables() == {"alembic_version", "users", "user_audit"}
    assert emails(db) == ["user1@example.com"]
    db.run(command.upgrade, "head")
    db.run(command.check)
